#!/bin/sh
# cf-tunnel: runs the Cloudflare Tunnel connector for cloudflare-npm.
#
# With TUNNEL_TOKEN set it simply runs that (dashboard-managed) tunnel.
# Otherwise it uses a locally-managed tunnel kept in $DIR (a volume):
#   1. no cert.pem yet  -> `cloudflared tunnel login`, printing a link to click
#   2. no tunnel yet    -> adopt the single credentials file in $DIR, or create
#                          tunnel $TUNNEL_NAME
#   3. write config.yml sending every hostname to $ORIGIN, then run the tunnel
set -eu

DIR=${CLOUDFLARED_DIR:-/root/.cloudflared}
ORIGIN=${ORIGIN:-http://nginx-proxy-manager:80}
TUNNEL_NAME=${TUNNEL_NAME:-cloudflare-npm}
CONFIG=$DIR/config.yml
MARK="# generated by cf-tunnel; edits are overwritten. Delete this line to manage the file yourself."

log() { echo "$(date -u +%FT%TZ) cf-tunnel: $*"; }
die() { log "FATAL $*"; sleep 60; exit 1; }  # sleep: avoid a tight restart loop

if [ -n "${TUNNEL_TOKEN:-}" ]; then
  log "running dashboard-managed tunnel from TUNNEL_TOKEN"
  exec cloudflared tunnel --no-autoupdate run
fi
unset TUNNEL_TOKEN
export TUNNEL_ORIGIN_CERT="$DIR/cert.pem"
mkdir -p "$DIR"

if [ ! -s "$DIR/cert.pem" ]; then
  log "not logged in to Cloudflare yet."
  log ">>> Open the URL below, sign in, and pick the domain to use. <<<"
  # HOME decides where login saves cert.pem ($HOME/.cloudflared).
  HOME=$(dirname "$DIR") cloudflared tunnel login || die "login failed or timed out; restart to get a new link"
  [ -s "$DIR/cert.pem" ] || die "login finished but $DIR/cert.pem is missing"
  log "logged in"
fi

tunnel_id=""
if [ -s "$CONFIG" ]; then
  tunnel_id=$(sed -n 's/^tunnel: *//p' "$CONFIG" | tr -d '"'"'"' ')
fi
if [ -z "$tunnel_id" ]; then
  # Exactly one credentials file here (e.g. moved from an older setup): adopt it.
  set -- "$DIR"/*-*-*-*-*.json
  if [ $# -eq 1 ] && [ -s "$1" ]; then
    tunnel_id=$(basename "$1" .json)
    log "using existing tunnel $tunnel_id"
  fi
fi
if [ -z "$tunnel_id" ]; then
  existing=$(cloudflared tunnel list -o json -n "$TUNNEL_NAME" | jq -r '.[0].id // empty')
  [ -z "$existing" ] || die "a tunnel named '$TUNNEL_NAME' already exists, but its credentials aren't in this folder. Set TUNNEL_NAME to a new name, or delete that tunnel in the Cloudflare dashboard."
  log "creating tunnel '$TUNNEL_NAME'"
  cloudflared tunnel create --credentials-file "$DIR/new.json" "$TUNNEL_NAME" >/dev/null
  tunnel_id=$(jq -r .TunnelID "$DIR/new.json")
  mv "$DIR/new.json" "$DIR/$tunnel_id.json"
  log "created tunnel $tunnel_id"
fi
[ -s "$DIR/$tunnel_id.json" ] || die "credentials $DIR/$tunnel_id.json not found"

if [ ! -s "$CONFIG" ] || head -1 "$CONFIG" | grep -qF "$MARK"; then
  cat > "$CONFIG" <<EOF
$MARK
tunnel: $tunnel_id
credentials-file: $DIR/$tunnel_id.json
ingress:
  - service: $ORIGIN
EOF
fi

log "running tunnel $tunnel_id -> $ORIGIN"
exec cloudflared tunnel --no-autoupdate --config "$CONFIG" run
